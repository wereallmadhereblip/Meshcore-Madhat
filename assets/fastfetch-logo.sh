#!/usr/bin/env bash

G1='\033[38;5;159m'
G2='\033[38;5;123m'
G3='\033[38;5;87m'
G4='\033[38;5;81m'
G5='\033[38;5;75m'
G6='\033[38;5;39m'
G7='\033[38;5;33m'
G8='\033[38;5;27m'
G9='\033[38;5;26m'
RESET='\033[0m'

draw_layer() {
  local color="$1"
  printf '%b' "$color"
   cat
}

draw_layer "$G1" <<'EOF'
                            :%@@-                                     
                            :-------@                                 
                   ---==    ---%#=-----@                              
EOF

draw_layer "$G2" <<'EOF'
                  +----:#   ---%@@@@#----@                            
                 @::-@----- :--@@@%@@@%---@                           
                 .::#%@#-::@@--=@%::#@@@--:.                          
EOF

draw_layer "$G3" <<'EOF'
                 .::%%%%%:::::::%%::::%%%:::@                         
                 %::*%%%%%%::::::%@:::*%%%-::                         
                 @:::%%%%%%%:::::#%*:::%%%:::=                        
EOF

draw_layer "$G4" <<'EOF'
                  ::::%%%%*+=:::::%%::-%%%=::@                        
                   @::::::::::::::#%+:%%%%=:::.@                      
                  :::::-#%%%%%%%%:%%-%%%%%:::::::                     
EOF

draw_layer "$G5" <<'EOF'
                =..+%%%%%%%%%%%%%%%%%%%%%:::#*:::=                   
              :..:+%%%%%%%%%%%%%%%%%%%%%%::::::%+:..:                 
              ...#%%%%%%#%%%%%%%%%%%%%##::::::-:=#.::#                
EOF

draw_layer "$G6" <<'EOF'
           =...:####%%%#:::+##%%###%%%##:::-:....:%::..               
        @:....=%%#####:...:::-##########::::--::--.#-...              
   @...=%########*##::.=############::...::::...#=...               
EOF

draw_layer "$G7" <<'EOF'
   @   .*##############################*..+=...:..-=:*:..%            
      #################################....:.++=+.:...*...@           
  =     ..############################=.....*-.::*....:*..            
       =*############################+...*:.........++.+=  +          
EOF

draw_layer "$G8" <<'EOF'
      ###**########################*.....-...........:..+             
      #######*######*#######*###**-......=....::: ...:. -+  -         
   -   -***###****###***##******... ..*+ -.*......*= :.=.+            
         :##*.         .  ....    ++= ...-.. .**- ...:...-+           
      :         =:.:     ..     .. -:.  .-  .:.=:.  .:  ..=           
          -@          -  .= ..  .  - ..  - ..  -  .  .    ==  :       
EOF

draw_layer "$G9" <<'EOF'
                          =-  -+.  -  =+ .-*.  =  == .-=   =          
                          =  .   -+++ .  :  .-*+= . ..   :==.  @      
                      :  :=:  : +=  :+.:  -.+=  :+.:  :.--  =         
                     #   =.:=-- :.  .: :+-= ::  .-.:=-- ..  =         
                        =.   .    .-     -     -     :     :--  %     
                       -:    .     :     -     :     :     : -        
                      -.   :==-    .   .+=-    :   .==:    . -.  @    
                 -   -: .-      =- :.=      =- :.=      -: ..--       
                =   -:--.        .==:        .==-        .--: -       
                   -      -.   =.  .  =.   =.  :  -.   -   :  --  +   
                  -:         .     .     :     :     :     :   -      
              @  .-          .     :     :     :     .     .  :-   =  
                 -           .    .:     :     :     .    :-.     .   
             =   - :.   .:-.  .-..   .-.   -.:   :-.  .::      -      
             -    .: .::.  :  :  .:::  :  :  .-::  :::      =         
               -     ::            .           ::-.     .             
                  -      :.        .     .   ::      #                
                     @.     :.     .     ::.     .                    
                        @.     ..     ..      .                       
                           #      ...                                 
                                       @                              
                                   .:_
EOF

printf '%b' "$RESET"